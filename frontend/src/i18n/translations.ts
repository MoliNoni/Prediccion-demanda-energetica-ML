export const translations: Record<Language, Record<TranslationKey, string>> = { en, es };

export type Translate = (key: TranslationKey, values?: Record<string, string>) => string;

export function createTranslate(lang: Language): Translate {
  return (key, values) => {
    const template = translations[lang][key];
    if (!values) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => values[name] ?? match);
  };
}
